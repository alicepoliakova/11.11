import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const SOURCE =
  process.argv[2] ??
  path.join(os.homedir(), "Downloads", "Transport_Froen_Antwerten.md");

const md = fs.readFileSync(SOURCE, "utf8");

const lines = md
  .split("\n")
  .filter((l) => l.trim().startsWith("|"))
  .slice(2); // drop header row + separator row

function splitCell(cell) {
  const match = cell.trim().match(/^(.*?)\s*\*(.+)\*$/s);
  if (!match) {
    throw new Error(`Could not split LU/RU in cell: ${cell}`);
  }
  return [match[1].trim(), match[2].replace(/\*/g, "").trim()];
}

const cards = lines.map((line) => {
  const cells = line
    .split("|")
    .map((c) => c.trim())
    .filter((_, i, arr) => i > 0 && i < arr.length - 1); // drop empty ends from leading/trailing "|"

  if (cells.length !== 2) {
    throw new Error(`Expected 2 cells, got ${cells.length}: ${line}`);
  }

  const [questionLu, questionRu] = splitCell(cells[0]);
  const [answerLu, answerRu] = splitCell(cells[1]);
  return [questionLu, questionRu, answerLu, answerRu];
});

const seedTopic = {
  id: "transport",
  name: "Transport",
  cards,
};

const output = `// Generated by scripts/extract-seed-transport.mjs from ${path.basename(SOURCE)} — do not hand-edit.
import type { SeedTopic } from "./seed-sproochen";

export const seedTopics: SeedTopic[] = ${JSON.stringify([seedTopic], null, 2)};
`;

const outPath = path.join(import.meta.dirname, "..", "data", "seed-transport.ts");
fs.writeFileSync(outPath, output);

console.log(`Wrote ${cards.length} card(s) to data/seed-transport.ts`);
